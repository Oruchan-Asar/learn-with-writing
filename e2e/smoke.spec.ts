import { expect, test, type Page } from "@playwright/test";
import type { TranscriptResponse } from "@/lib/transcript/types";

// A short, embeddable video. Its captions are replaced with the cues below,
// so the test doesn't depend on YouTube's caption API or its rate limits.
const VIDEO_ID = "jNQXAC9IVRw";

const FAKE_TRANSCRIPT: TranscriptResponse = {
  videoId: VIDEO_ID,
  title: "Smoke test video",
  track: { code: "en", name: "English", isAutoGenerated: false },
  tracks: [{ code: "en", name: "English", isAutoGenerated: false }],
  cues: [
    { start: 0, end: 2, text: "The kettle sang a quiet song." },
    { start: 2.2, end: 5, text: "Two cups waited on the table." },
    { start: 5.5, end: 9, text: "Nobody was in a hurry today." },
  ],
};

async function mockTranscript(page: Page, response: { status: number; body: unknown }) {
  await page.route("**/api/transcript?**", (route) =>
    route.fulfill({ status: response.status, contentType: "application/json", body: JSON.stringify(response.body) }),
  );
}

const statusLine = (page: Page) => page.locator("p[aria-live=polite]");
const clock = (page: Page) => page.getByText(/\d+:\d{2} \/ \d+:\d{2} · /);

test("pauses at the end of a segment and resumes once it's typed", async ({ page }) => {
  await mockTranscript(page, { status: 200, body: FAKE_TRANSCRIPT });

  // Paste a link on the home page.
  await page.goto("/");
  await page.getByLabel("YouTube video link").fill(`https://youtu.be/${VIDEO_ID}`);
  await page.getByRole("button", { name: "Start" }).click();
  await expect(page).toHaveURL(new RegExp(`/watch/${VIDEO_ID}$`));
  await expect(page.getByText("Segment 1 / 3")).toBeVisible();

  // The first start must be a click on the video itself. YouTube shows its play
  // button a moment before it reacts to clicks, so click again if needed.
  await expect(page.getByText("Click the video to start it.")).toBeVisible();
  const playButton = page.frameLocator("iframe").getByRole("button", { name: "Play video" });
  await expect(async () => {
    await playButton.click({ timeout: 2_000 });
    await expect(clock(page)).not.toContainText("Not started", { timeout: 2_000 });
  }).toPass({ timeout: 20_000 });

  // Nothing is typed, so the video waits at the end of segment 1.
  await expect(statusLine(page)).toHaveText(/finish typing to continue/);
  await expect(clock(page)).toContainText("Paused");

  // Type it (spaces are optional, a wrong letter has to be fixed), and the video plays on.
  const input = page.getByLabel("Type the sentence");
  await input.focus();
  await page.keyboard.type("the kettle sang a quiet sx");
  await page.keyboard.press("Backspace");
  await page.keyboard.type("ong");
  await expect(clock(page)).toContainText("Playing");
  await expect(page.getByText("Segment 2 / 3")).toBeVisible();

  // It counted the mistake.
  await expect(page.getByText(/1 typed/)).toBeVisible();
  await expect(page.getByText(/9\d% accuracy/)).toBeVisible();
});

test("offers a subtitle upload when captions can't be loaded", async ({ page }) => {
  await mockTranscript(page, { status: 404, body: { error: "This video has no captions." } });
  await page.goto(`/watch/${VIDEO_ID}`);

  await expect(page.getByText("This video has no captions.")).toBeVisible();
  await page.locator("input[type=file]").setInputFiles({
    name: "test.srt",
    mimeType: "application/x-subrip",
    buffer: Buffer.from("1\n00:00:00,500 --> 00:00:02,000\nA paper boat sailed away.\n"),
  });
  await expect(page.getByText("1 segments · from test.srt")).toBeVisible();
  await expect(page.getByLabel("Type the sentence")).toBeAttached();
});

test("shows friendly errors for bad links", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("YouTube video link").fill("https://vimeo.com/123");
  await page.getByRole("button", { name: "Start" }).click();
  await expect(page.getByText("That doesn't look like a YouTube video link.")).toBeVisible();

  await page.goto("/watch/not-valid");
  await expect(page.getByRole("heading", { name: "That page doesn't exist" })).toBeVisible();
});
