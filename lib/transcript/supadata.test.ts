import { describe, expect, it, vi } from "vitest";
import { TranscriptError } from "./provider";
import { SupadataTranscriptProvider } from "./supadata";

const json = (status: number, body: unknown) =>
  new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });

const TRANSCRIPT = {
  content: [
    { text: "The lighthouse blinked twice.", offset: 1000, duration: 2500, lang: "en" },
    { text: "  ", offset: 3500, duration: 500, lang: "en" },
    { text: "Then the fog rolled in.", offset: 4000, duration: 3000, lang: "en" },
  ],
  lang: "en",
  availableLangs: ["en", "de"],
};

/** A provider whose HTTP calls return the given responses in order. */
function providerWith(...responses: Response[]) {
  const fetchMock = vi.fn<typeof fetch>();
  for (const r of responses) fetchMock.mockResolvedValueOnce(r);
  const provider = new SupadataTranscriptProvider("test-key", { fetch: fetchMock, sleep: async () => {} });
  return { provider, fetchMock };
}

async function errorOf(promise: Promise<unknown>): Promise<TranscriptError> {
  const err = await promise.then(
    () => null,
    (e: unknown) => e,
  );
  expect(err).toBeInstanceOf(TranscriptError);
  return err as TranscriptError;
}

describe("SupadataTranscriptProvider", () => {
  it("turns chunks into cues in seconds, dropping empty ones", async () => {
    const { provider } = providerWith(json(200, TRANSCRIPT));
    const result = await provider.fetch("abcdefghijk");
    expect(result.cues).toEqual([
      { start: 1, end: 3.5, text: "The lighthouse blinked twice." },
      { start: 4, end: 7, text: "Then the fog rolled in." },
    ]);
    expect(result.track).toEqual({ code: "en", name: "English", isAutoGenerated: false });
    expect(result.tracks.map((t) => t.name)).toEqual(["English", "German"]);
    expect(result.title).toBe("");
  });

  it("asks for native captions of the video, with the key and a two-letter language", async () => {
    const { provider, fetchMock } = providerWith(json(200, TRANSCRIPT));
    await provider.fetch("abcdefghijk", "pt-BR");
    const [url, init] = fetchMock.mock.calls[0];
    const params = new URL(String(url)).searchParams;
    expect(String(url)).toMatch(/^https:\/\/api\.supadata\.ai\/v1\/transcript\?/);
    expect(params.get("url")).toBe("https://www.youtube.com/watch?v=abcdefghijk");
    expect(params.get("mode")).toBe("native");
    expect(params.get("lang")).toBe("pt");
    expect(init?.headers).toEqual({ "x-api-key": "test-key" });
  });

  it("polls a job for long videos until it completes", async () => {
    const { provider, fetchMock } = providerWith(
      json(202, { jobId: "job 1" }),
      json(200, { status: "queued" }),
      json(200, { status: "active" }),
      json(200, { status: "completed", ...TRANSCRIPT }),
    );
    const result = await provider.fetch("abcdefghijk");
    expect(result.cues).toHaveLength(2);
    expect(String(fetchMock.mock.calls[1][0])).toBe("https://api.supadata.ai/v1/transcript/job%201");
  });

  it("reports a failed job", async () => {
    const { provider } = providerWith(json(202, { jobId: "j" }), json(200, { status: "failed", error: { message: "Nope." } }));
    expect((await errorOf(provider.fetch("abcdefghijk"))).message).toBe("Nope.");
  });

  it.each([
    [206, "no_captions"],
    [404, "unavailable"],
    [401, "upstream"],
    [402, "upstream"],
    [429, "upstream"],
    [500, "upstream"],
  ])("maps HTTP %s to %s", async (status, code) => {
    const { provider } = providerWith(json(status, { error: "x", message: "Service said no." }));
    expect((await errorOf(provider.fetch("abcdefghijk"))).code).toBe(code);
  });

  it("explains a bad key and a used-up quota", async () => {
    expect((await errorOf(providerWith(json(401, {})).provider.fetch("abcdefghijk"))).message).toMatch(/API key/);
    expect((await errorOf(providerWith(json(429, {})).provider.fetch("abcdefghijk"))).message).toMatch(/quota/);
  });

  it("reports a network failure", async () => {
    const fetchMock = vi.fn<typeof fetch>().mockRejectedValue(new TypeError("fetch failed"));
    const provider = new SupadataTranscriptProvider("k", { fetch: fetchMock });
    expect((await errorOf(provider.fetch("abcdefghijk"))).message).toMatch(/Could not reach/);
  });

  it("treats a transcript with no text as no captions", async () => {
    const { provider } = providerWith(json(200, { content: [], lang: "en", availableLangs: [] }));
    expect((await errorOf(provider.fetch("abcdefghijk"))).code).toBe("no_captions");
  });
});
