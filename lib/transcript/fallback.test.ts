import { describe, expect, it, vi } from "vitest";
import { FallbackTranscriptProvider } from "./fallback";
import { isBotCheck, TranscriptError, type TranscriptErrorCode, type TranscriptProvider } from "./provider";
import type { TranscriptResponse } from "./types";

const RESPONSE: TranscriptResponse = {
  videoId: "abcdefghijk",
  title: "",
  track: { code: "en", name: "English", isAutoGenerated: false },
  tracks: [],
  cues: [{ start: 0, end: 1, text: "Hello." }],
};

const succeeding = (): TranscriptProvider => ({ fetch: vi.fn().mockResolvedValue(RESPONSE) });
const failing = (code: TranscriptErrorCode, message: string = code): TranscriptProvider => ({
  fetch: vi.fn().mockRejectedValue(new TranscriptError(code, message)),
});

describe("FallbackTranscriptProvider", () => {
  it("uses the first provider that succeeds", async () => {
    const second = succeeding();
    await expect(new FallbackTranscriptProvider([succeeding(), second]).fetch("abcdefghijk")).resolves.toBe(RESPONSE);
    expect(second.fetch).not.toHaveBeenCalled();
  });

  it("falls back when the first is blocked, passing on the language", async () => {
    const second = succeeding();
    await expect(new FallbackTranscriptProvider([failing("blocked"), second]).fetch("abcdefghijk", "de")).resolves.toBe(
      RESPONSE,
    );
    expect(second.fetch).toHaveBeenCalledWith("abcdefghijk", "de");
  });

  it("doesn't ask further providers when the video has no captions", async () => {
    const second = succeeding();
    await expect(new FallbackTranscriptProvider([failing("no_captions"), second]).fetch("abcdefghijk")).rejects.toMatchObject({
      code: "no_captions",
    });
    expect(second.fetch).not.toHaveBeenCalled();
  });

  it("prefers an answer about the video over a provider failure", async () => {
    await expect(
      new FallbackTranscriptProvider([failing("blocked"), failing("unavailable")]).fetch("abcdefghijk"),
    ).rejects.toMatchObject({ code: "unavailable" });
  });

  it("otherwise reports the last provider's error", async () => {
    await expect(
      new FallbackTranscriptProvider([failing("blocked"), failing("upstream", "quota used up")]).fetch("abcdefghijk"),
    ).rejects.toMatchObject({ message: "quota used up" });
  });

  it("wraps unexpected errors", async () => {
    const broken: TranscriptProvider = { fetch: vi.fn().mockRejectedValue(new Error("boom")) };
    await expect(new FallbackTranscriptProvider([broken]).fetch("abcdefghijk")).rejects.toMatchObject({
      code: "upstream",
      message: "boom",
    });
  });
});

describe("isBotCheck", () => {
  it.each([
    ["Sign in to confirm you’re not a bot", true],
    ["Sign in to confirm your age", true],
    ["Our systems have detected unusual traffic", true],
    ["This video is unavailable", false],
    ["Video unavailable. This video is private.", false],
  ])("%j → %s", (reason, expected) => {
    expect(isBotCheck(reason)).toBe(expected);
  });
});
