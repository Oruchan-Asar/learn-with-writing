/** One timed caption line as YouTube delivers it. Times are in seconds. */
export type Cue = {
  start: number;
  end: number;
  text: string;
};

/** A typable piece of the transcript, built from one or more cues. */
export type Segment = {
  id: number;
  start: number;
  end: number;
  text: string;
};

export type TranscriptTrack = {
  /** Language code, e.g. "en" or "pt-BR". */
  code: string;
  name: string;
  isAutoGenerated: boolean;
};

export type TranscriptResponse = {
  videoId: string;
  title: string;
  /** The track the cues come from. */
  track: TranscriptTrack;
  /** Every caption track the video has, for switching language. */
  tracks: TranscriptTrack[];
  cues: Cue[];
};

export type TranscriptErrorResponse = {
  error: string;
};
